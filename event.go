// Package audit provides shared audit types for event logging across services.
// This package is the producer-facing contract — both the audit service and
// producer services import these types without depending on internal/audit/.
package audit

import (
	"errors"
	"fmt"
	"net"
	"time"

	"github.com/google/uuid"
)

// Outcome constants represent the result of an audited action.
//
// Domain-specific action and resource type constants are defined in their respective packages:
// - Auth actions (login, 2fa, password): internal/auth/app/audit/auth/events.go
// - Scope actions: internal/auth/app/audit/scopes/events.go
// - OAuth actions: internal/auth/app/audit/oauth/events.go
// - BFF actions: internal/auth/app/audit/bff/events.go
// Every audit event must have exactly one outcome value.
const (
	// OutcomeSuccess indicates the action completed successfully.
	// Example: User logged in with valid credentials and 2FA code.
	OutcomeSuccess = "success"

	// OutcomeFailure indicates the action failed to complete.
	// Example: Login attempt with invalid password, token refresh with expired token.
	// Should include FailureReason field with specific error details.
	OutcomeFailure = "failure"

	// OutcomePartial indicates the action partially succeeded but requires follow-up.
	// Example: Password reset email sent but SMTP had transient errors.
	// Should include FailureReason field explaining what partially succeeded.
	OutcomePartial = "partial"
)

// AuditEvent represents a security-relevant action in the authentication system before enrichment.
// Events are immutable once created and capture the core details of what happened.
//
// Design principles:
// - Immutable after creation (no setters, only constructed via NewEventBuilder)
// - UUID v7 for time-sortable IDs with embedded timestamp
// - Nullable UserID for failed authentication attempts
// - Action and Outcome are required for all events
type AuditEvent struct {
	// Core required fields
	ID            uuid.UUID  `json:"id"`             // UUID v7 for time-sortable IDs
	UserID        *uuid.UUID `json:"user_id"`        // Actor who performed the action (nullable for failed logins)
	Action        string     `json:"action"`         // Event type (login_success, password_change, etc.)
	ResourceType  string     `json:"resource_type"`  // Type of resource affected (user, session, token)
	ResourceID    *uuid.UUID `json:"resource_id"`    // Specific resource instance (nullable)
	Outcome       string     `json:"result"`         // success, failure, partial (maps to "result" in DB)
	FailureReason string     `json:"failure_reason"` // Reason for failure (populated on errors)
	Timestamp     time.Time  `json:"created_at"`     // When the event occurred (maps to "created_at" in DB)

	// HTTP context (populated by middleware)
	IPAddress *string   `json:"ip_address"` // Client IP address (nullable - not all events have HTTP context)
	UserAgent string    `json:"user_agent"` // Client user agent
	RequestID uuid.UUID `json:"request_id"` // Trace ID for request correlation (always present)

	// Context data (populated by application code, enriched by enrichers)
	ContextData map[string]interface{} `json:"metadata"` // Application-specific context (maps to "metadata" in DB)

	// Delivery semantics
	Critical bool `json:"critical"` // If true, Log() rejects the operation when all writers fail (FR12/NFR24)
}

// FinalAuditEvent is a fully enriched audit event ready for storage.
// It embeds the original AuditEvent and adds enrichment tracking metadata.
//
// The enrichment process:
// 1. Router receives AuditEvent
// 2. Enrichers add metadata to EnrichmentMetadata map
// 3. FinalAuditEvent created with enrichment timestamp
// 4. Writers set WrittenAt timestamp on successful write
type FinalAuditEvent struct {
	AuditEvent                                // Embedded original event
	EnrichmentMetadata map[string]interface{} `json:"enrichment_metadata"` // Consolidated metadata from all enrichers
	EnrichedAt         time.Time              `json:"enriched_at"`         // When enrichment completed
	WrittenAt          *time.Time             `json:"written_at"`          // When written to storage (nullable, set by writers)
}

// Validate checks if the AuditEvent has all required fields and valid values.
// Returns error if validation fails.
// Note: ID is not validated as it's generated by the database on INSERT
func (e *AuditEvent) Validate() error {
	// Validate Action is not empty
	if e.Action == "" {
		return errors.New("audit event action is required")
	}

	// Validate Outcome
	if e.Outcome != OutcomeSuccess && e.Outcome != OutcomeFailure && e.Outcome != OutcomePartial {
		return fmt.Errorf("invalid audit event outcome: %s (must be success, failure, or partial)", e.Outcome)
	}

	// Validate IP address format if provided
	if e.IPAddress != nil && *e.IPAddress != "" {
		if ip := net.ParseIP(*e.IPAddress); ip == nil {
			return fmt.Errorf("invalid IP address: %s", *e.IPAddress)
		}
	}

	// Validate timestamp is not zero
	if e.Timestamp.IsZero() {
		return errors.New("audit event timestamp is required")
	}

	// Validate RequestID if present
	if e.RequestID == uuid.Nil {
		return errors.New("audit event request ID is required")
	}

	return nil
}

// Validate checks if the FinalAuditEvent is valid for storage.
func (f *FinalAuditEvent) Validate() error {
	// Validate embedded AuditEvent
	if err := f.AuditEvent.Validate(); err != nil {
		return fmt.Errorf("invalid audit event: %w", err)
	}

	// Validate EnrichedAt is after Timestamp
	if !f.EnrichedAt.After(f.Timestamp) && !f.EnrichedAt.Equal(f.Timestamp) {
		return errors.New("enrichment timestamp must be >= event timestamp")
	}

	// Validate EnrichmentMetadata size (max 10KB)
	// Note: This is a rough estimate, actual JSON size may vary
	if f.EnrichmentMetadata != nil {
		// Simple size check - count nested map entries
		if len(f.EnrichmentMetadata) > 100 {
			return errors.New("enrichment metadata exceeds maximum size (100 top-level keys)")
		}
	}

	return nil
}

// EventBuilder provides a fluent interface for constructing audit events with standardized field ordering.
// This ensures consistency across all audit event creation and reduces duplication.
//
// Usage:
//
//	event := audit.NewEventBuilder().
//	    WithUser(userID).
//	    WithAction("login").
//	    WithResource("session", &sessionID).
//	    WithSuccess().
//	    WithHTTPContext(ipAddress, userAgent).
//	    WithContext(map[string]interface{}{"email": "user@example.com"}).
//	    Build()
type EventBuilder struct {
	event *AuditEvent
}

// NewEventBuilder creates a new EventBuilder with required base fields initialized.
// The requestID is extracted from context if available, otherwise generates a new one.
func NewEventBuilder() *EventBuilder {
	return &EventBuilder{
		event: &AuditEvent{
			ID:          uuid.Must(uuid.NewV7()), // Generate UUID v7 with embedded timestamp
			Timestamp:   time.Now().UTC(),
			RequestID:   uuid.Must(uuid.NewV7()), // Will be overridden by middleware if present
			ContextData: make(map[string]interface{}),
		},
	}
}

// WithUser sets the user who performed the action.
func (b *EventBuilder) WithUser(userID uuid.UUID) *EventBuilder {
	b.event.UserID = &userID
	return b
}

// WithAction sets the action being audited.
func (b *EventBuilder) WithAction(action string) *EventBuilder {
	b.event.Action = action
	return b
}

// WithResource sets the resource type and optional resource ID.
func (b *EventBuilder) WithResource(resourceType string, resourceID *uuid.UUID) *EventBuilder {
	b.event.ResourceType = resourceType
	b.event.ResourceID = resourceID
	return b
}

// WithSuccess marks the event as successful.
func (b *EventBuilder) WithSuccess() *EventBuilder {
	b.event.Outcome = OutcomeSuccess
	return b
}

// WithFailure marks the event as failed with a reason.
func (b *EventBuilder) WithFailure(reason string) *EventBuilder {
	b.event.Outcome = OutcomeFailure
	b.event.FailureReason = reason
	return b
}

// WithPartial marks the event as partially successful.
func (b *EventBuilder) WithPartial(reason string) *EventBuilder {
	b.event.Outcome = OutcomePartial
	b.event.FailureReason = reason
	return b
}

// WithHTTPContext adds HTTP-specific context (IP address and user agent).
func (b *EventBuilder) WithHTTPContext(ipAddress, userAgent string) *EventBuilder {
	if ipAddress != "" {
		b.event.IPAddress = &ipAddress
	}
	b.event.UserAgent = userAgent
	return b
}

// WithRequestID sets a specific request ID (typically from middleware).
func (b *EventBuilder) WithRequestID(requestID uuid.UUID) *EventBuilder {
	b.event.RequestID = requestID
	return b
}

// WithContext adds arbitrary context data.
func (b *EventBuilder) WithContext(data map[string]interface{}) *EventBuilder {
	for k, v := range data {
		b.event.ContextData[k] = v
	}
	return b
}

// WithContextValue adds a single context key-value pair.
func (b *EventBuilder) WithContextValue(key string, value interface{}) *EventBuilder {
	b.event.ContextData[key] = value
	return b
}

// WithCritical marks the event as compliance-critical. When all delivery channels
// fail, Log() returns an error so the producer can reject the originating operation.
// Events without WithCritical() default to best-effort delivery (FR13).
func (b *EventBuilder) WithCritical() *EventBuilder {
	b.event.Critical = true
	return b
}

// Build returns the constructed audit event.
// Note: Does not validate - validation happens at the router level.
func (b *EventBuilder) Build() *AuditEvent {
	return b.event
}
